function sha256(value: string): string {
  return crypto.createHash('sha256').update(value).digest('hex')
}

function randomToken(): string {
  return crypto.randomBytes(32).toString('hex')
}

function publicBaseUrl(): string {
  if (config.sandbox.callbackUrl) {
    const base = config.sandbox.callbackUrl.replace(/\/api\/sandboxes\/callback$/, '')
    if (base) return base
  }
  return config.appUrl
}

function templateFor(jobType: string, language?: string): string {
  if (language && config.sandbox.templates[language]) return config.sandbox.templates[language]
  return config.sandbox.templates[jobType] ?? ''
}

function defaultPrompt(input: { jobType: string; language?: string }): string {
  if (input.jobType === 'docs') {
    return [
      'Build the API documentation for the spec in this workspace.',
      'Use the docs-builder skill and follow its completion protocol.',
      'Write clear, complete reference docs and verify they build.',
    ].join(' ')
  }
  return [
    'Build a production-grade SDK from the API spec in this workspace.',
    `Use the sdk-builder skill and follow its completion protocol.`,
    'Ensure tests and lint pass before finishing.',
  ].join(' ')
}

