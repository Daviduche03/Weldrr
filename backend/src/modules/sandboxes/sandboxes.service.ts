function discoveryPrompt(input: { name: string; targetUrl?: string | null }): string {
  const target = input.targetUrl
    ? `the API documentation at ${input.targetUrl}`
    : 'the codebase in /workspace'
  return [
    `Run Weldrr discovery for "${input.name}".`,
    `Analyze ${target} and produce a complete /workspace/docs.md following the discovery-agent skill.`,
    'Include every endpoint with its request body and responses. When docs.md is complete, call report_sdk_complete with status "finished".',
  ].join(' ')
}

async function waitForDiscovery(projectId: string | null, timeoutMs = 90_000): Promise<string | undefined> {
  if (!projectId) return undefined
  const deadline = Date.now() + timeoutMs
  while (Date.now() < deadline) {
    const discovery = await discoveryRepository.latestForProject(projectId)
    if (discovery) {
      if (discovery.status === 'ready' && discovery.docsMarkdown) {
        return discovery.docsMarkdown
      }
      if (discovery.status === 'failed') {
        logger.warn({ projectId }, 'Discovery failed — continuing without docs.md')
        return undefined
      }
    }
    await new Promise((resolve) => setTimeout(resolve, 1_000))
  }
  logger.warn({ projectId }, 'Timed out waiting for discovery — continuing without docs.md')
  return undefined
}

async function prepareGitPush(
  project: Project,
  jobType: 'sdk' | 'docs',
  language?: string,
): Promise<{ gitRemote: string; gitToken: string } | null> {
  if (!project.gitRepo) return null

  const connection = await githubRepository.findForWorkspace(project.workspaceId)
  if (!connection?.accessToken) {
    logger.warn(
      { projectId: project.id, workspaceId: project.workspaceId },
      'No GitHub connection for workspace — artifact will not be pushed',
    )
    return null
  }

  const kind = jobType === 'docs' ? 'docs' : 'sdk'
  const baseName =
    kind === 'docs'
      ? `${slugify(project.name) || 'project'}-docs`
      : `${slugify(project.name) || 'project'}-sdk${language ? `-${slugify(language)}` : ''}`
  const isPrivate = project.gitRepo.private

  let repo: { cloneUrl: string } | null = null
  for (let attempt = 0; attempt < 5 && !repo; attempt += 1) {
    const name = attempt === 0 ? baseName : `${baseName}-${attempt + 1}`
    try {
      repo = await createGitHubRepo(connection.accessToken, {
        name,
        description: `Weldrr-generated ${language ?? ''} SDK for ${project.name}`.trim(),
        private: isPrivate,
      })
    } catch (err) {
      const isConflict = err instanceof AppError && err.statusCode === 409
      if (!isConflict) throw err
      if (attempt === 4) throw err
    }
  }

  if (!repo) return null
  logger.info({ projectId: project.id, repo: repo.cloneUrl }, 'SDK repo ready for push')
  return { gitRemote: repo.cloneUrl, gitToken: connection.accessToken }
}

export const sandboxService = {
  async list(workspaceId: string, query: SandboxQuery) {
    const offset = offsetForPage(query.page, query.limit)
    const { data, total } = await sandboxRepository.findAll({
      workspaceId,
      offset,
      limit: query.limit,
      jobType: query.jobType,
      status: query.status,
      projectId: query.projectId,
      sortOrder: 'desc',
    })

    return {
      data: data.map(toSandboxResponse),
      meta: {
        page: query.page,
        limit: query.limit,
        total,
        totalPages: totalPages(total, query.limit),
      },
    }
  },

  async getById(workspaceId: string, id: string): Promise<SandboxResponse> {
    const row = await sandboxRepository.findById(workspaceId, id)
    if (!row) throw new NotFoundError('Sandbox not found')
    return toSandboxResponse(row)
  },

  async issue(workspaceId: string, input: CreateSandboxInput): Promise<SandboxResponse> {
    let project: Project | undefined
    if (input.projectId) {
      project = await projectRepository.findById(workspaceId, input.projectId)
      if (!project) throw new NotFoundError('Project not found')
    }

    const callbackToken = randomToken()
    const opencodePassword = randomToken()

    let artifactVersion: string | undefined
    if (project && input.jobType === 'sdk') {
      const latest = await versionRepository.latestForProject(project.id, 'sdk')
      artifactVersion = nextVersion(latest?.version, 'patch')
    } else if (project && input.jobType === 'docs') {
      artifactVersion = project.docsVersion ?? undefined
    }

    const row = await sandboxRepository.create({
      workspaceId,
      projectId: input.projectId ?? null,
      jobType: input.jobType,
      language: input.language ?? null,
      spec: input.spec ?? null,
      status: 'issuing',
      modalSandboxId: null,
      tunnelUrl: null,
      opencodePassword: encryptSecret(opencodePassword),
      callbackTokenHash: sha256(callbackToken),
      version: artifactVersion ?? null,
      error: null,
      startedAt: null,
      finishedAt: null,
    })

    const baseUrl = publicBaseUrl()
    const gitTemplate = templateFor(input.jobType, input.language)
    const callbackUrl = `${baseUrl}/api/sandboxes/callback`
    const bootstrapUrl = `${baseUrl}/api/sandboxes/${row.id}/bootstrap?token=${callbackToken}`

    let gitRemote: string | undefined
    let gitToken: string | undefined
    if (project && (input.jobType === 'sdk' || input.jobType === 'docs')) {
      const push = await prepareGitPush(project, input.jobType, input.language).catch((err) => {
        logger.warn({ err, projectId: project.id }, 'Failed to prepare GitHub push — continuing without push')
        return null
      })
      gitRemote = push?.gitRemote
      gitToken = push?.gitToken
    }

    try {
      const provisioned = await provisionSandbox({
        sandboxId: row.id,
        jobType: input.jobType,
        callbackUrl,
        callbackToken,
        bootstrapUrl,
        gitTemplate,
        opencodePassword,
        ...(gitRemote ? { gitRemote } : {}),
        ...(gitToken ? { gitToken } : {}),
        ...(artifactVersion ? { artifactVersion } : {}),
      })

      await sandboxRepository.update(workspaceId, row.id, {
        status: 'ready',
        modalSandboxId: provisioned.sandboxId,
        tunnelUrl: provisioned.tunnelUrl,
        startedAt: new Date(),
      })

      await activityService.record({
        workspaceId,
        projectId: input.projectId ?? null,
        projectName: input.jobType === 'docs' ? 'Documentation sandbox' : 'SDK sandbox',
        action: 'created',
        detail: `Agent sandbox issued (${input.jobType}${input.language ? ` · ${input.language}` : ''})`,
      })

      const updated = await sandboxRepository.findById(workspaceId, row.id)
      return toSandboxResponse(updated ?? row)
    } catch (err) {
      await sandboxRepository.update(workspaceId, row.id, {
        status: 'failed',
        error: err instanceof Error ? err.message : 'Sandbox provisioning failed',
        finishedAt: new Date(),
      })
      throw err
    }
  },

  async start(
    workspaceId: string,
    id: string,
    input: StartSandboxInput,
  ): Promise<{ sessionId: string; tunnelUrl: string }> {
    const row = await sandboxRepository.findById(workspaceId, id)
    if (!row) throw new NotFoundError('Sandbox not found')
    if (row.status !== 'ready' && row.status !== 'building') {
      throw new AppError(409, `Sandbox is not ready to start (status: ${row.status})`)
    }
    if (!row.tunnelUrl || !row.opencodePassword) {
      throw new AppError(409, 'Sandbox has no opencode endpoint configured')
    }

    const password = decryptSecret(row.opencodePassword)
    await opencodeHealth(row.tunnelUrl, password)
    const sessionId = await opencodeCreateSession(
      row.tunnelUrl,
      password,
      `weldrr-${row.id}`,
    )
    await opencodeSendPrompt(
      row.tunnelUrl,
      password,
      sessionId,
      input.prompt,
      discoverySystemPrompt(),
    )

    await sandboxRepository.update(workspaceId, row.id, { status: 'building' })
    return { sessionId, tunnelUrl: row.tunnelUrl }
  },

  async terminate(workspaceId: string, id: string): Promise<SandboxResponse> {
    const row = await sandboxRepository.findById(workspaceId, id)
    if (!row) throw new NotFoundError('Sandbox not found')

    if (row.modalSandboxId && row.status !== 'terminated') {
      await terminateModalSandbox(row.modalSandboxId)
    }

    const updated = await sandboxRepository.update(workspaceId, id, {
      status: 'terminated',
      finishedAt: new Date(),
    })

    await activityService.record({
      workspaceId,
      projectId: row.projectId,
      projectName: row.jobType === 'docs' ? 'Documentation sandbox' : 'SDK sandbox',
      action: 'deleted',
      detail: `Agent sandbox terminated`,
    })

    return toSandboxResponse(updated ?? row)
  },

  async remove(workspaceId: string, id: string): Promise<void> {
    const row = await sandboxRepository.findById(workspaceId, id)
    if (!row) throw new NotFoundError('Sandbox not found')

    if (row.modalSandboxId && row.status !== 'terminated') {
      await terminateModalSandbox(row.modalSandboxId)
    }
    await sandboxRepository.delete(workspaceId, id)
  },

  async bootstrap(id: string, token: string): Promise<string> {
    const row = await sandboxRepository.findByIdGlobal(id)
    if (!row) throw new NotFoundError('Sandbox not found')
    if (sha256(token) !== row.callbackTokenHash) {
      throw new AppError(401, 'Invalid or expired token')
    }

    const docsMarkdown = await waitForDiscovery(row.projectId, 30_000)

    let spec = row.spec ?? undefined
    if (row.projectId) {
      const project = await projectRepository.findByIdGlobal(row.projectId)
      if (project) {
        spec =
          project.spec ??
          (project.specRaw ? parseSpec(project.specRaw) : undefined) ??
          undefined
      }
    }

    return bootstrapScript({
      model: config.sandbox.opencodeModel,
      providerApiKey: config.sandbox.providerApiKey,
      jobType: row.jobType,
      sandboxId: row.id,
      spec,
      docsMarkdown,
    })
  },

  async handleCallback(input: CallbackInput): Promise<SandboxResponse> {
    const row = await sandboxRepository.findByIdGlobal(input.sandboxId)
    if (!row) throw new NotFoundError('Sandbox not found')
    if (sha256(input.token) !== row.callbackTokenHash) {
      throw new AppError(401, 'Invalid or expired token')
    }
    if (row.status === 'finished' || row.status === 'failed' || row.status === 'terminated') {
      return toSandboxResponse(row)
    }

    const terminalStatus: Sandbox['status'] = input.status === 'failed' ? 'failed' : 'finished'
    const updated = await sandboxRepository.updateGlobal(row.id, {
      status: terminalStatus,
      error: input.status === 'failed' ? (input.summary ?? 'Agent reported failure') : null,
      artifactUrl: input.artifactUrl ?? null,
      finishedAt: new Date(),
    })

    if (row.jobType === 'discovery' && input.status === 'finished') {
      const discoveryReady = await handleAgentDiscoveryComplete(row)
      if (discoveryReady && row.projectId) {
        const project = await projectRepository.findByIdGlobal(row.projectId)
        if (project) {
          void autoStartArtifactBuilds(project, row.workspaceId)
        }
      }
    }

    if (
      row.jobType === 'sdk' &&
      terminalStatus === 'finished' &&
      row.version &&
      row.projectId
    ) {
      const existing = await versionRepository.findBySandboxId(row.id)
      if (!existing) {
        await versionRepository.create({
          workspaceId: row.workspaceId,
          projectId: row.projectId,
          artifactType: 'sdk',
          version: row.version,
          artifactUrl: input.artifactUrl ?? null,
          sandboxId: row.id,
          notes: input.summary ?? null,
        })
        await projectRepository.update(row.workspaceId, row.projectId, {
          sdkVersion: row.version,
        })
      }
    }

    if (
      row.jobType === 'docs' &&
      terminalStatus === 'finished' &&
      input.artifactUrl &&
      row.projectId
    ) {
      await projectRepository.update(row.workspaceId, row.projectId, {
        docsUrl: input.artifactUrl,
      })
    }

    if (row.projectId && row.jobType !== 'discovery') {
      await projectRepository.update(row.workspaceId, row.projectId, {
        status: terminalStatus === 'failed' ? 'failed' : 'ready',
      })
    }

    await activityService.record({
      workspaceId: row.workspaceId,
      projectId: row.projectId,
      projectName: row.jobType === 'docs' ? 'Documentation sandbox' : 'SDK sandbox',
      action: terminalStatus === 'failed' ? 'failed' : 'generated',
      detail:
        terminalStatus === 'failed'
          ? `Agent sandbox reported failure`
          : `Agent sandbox finished building${input.artifactUrl ? ` — ${input.artifactUrl}` : ''}`,
    })

    return toSandboxResponse(updated ?? row)
  },

  defaultPrompt,
}

function parseDocsMarkdownEndpoints(md: string): DiscoveryEndpoint[] {
  const endpoints: DiscoveryEndpoint[] = []
  const re = /### `(GET|POST|PUT|PATCH|DELETE|HEAD|OPTIONS|PUBLISH|SUBSCRIBE)\s+(\S+)`/gi
  let m: RegExpExecArray | null
  while ((m = re.exec(md)) !== null) {
    endpoints.push({
      method: m[1],
      path: m[2],
      summary: null,
      operationId: null,
      requestBody: null,
      responses: [],
      auth: null,
    })
  }
  return endpoints
}

async function handleAgentDiscoveryComplete(row: Sandbox): Promise<boolean> {
  if (!row.modalSandboxId || !row.projectId) return false
  const discovery = await discoveryRepository.findBySandboxId(row.id)
  if (!discovery) return false

  try {
    const docsMarkdown = await readSandboxFile(row.modalSandboxId, '/workspace/docs.md')
    if (!docsMarkdown.trim()) throw new Error('docs.md is empty')
    const endpoints = parseDocsMarkdownEndpoints(docsMarkdown)
    await discoveryRepository.update(discovery.id, {
      status: 'ready',
      docsMarkdown,
      endpoints,
    })
    await recordDocsVersion({
      workspaceId: row.workspaceId,
      projectId: row.projectId,
      discoveryId: discovery.id,
    })
    logger.info({ sandboxId: row.id }, 'Discovery agent docs.md saved')
    return true
  } catch (err) {
    logger.error({ err, sandboxId: row.id }, 'Failed to read discovery docs.md')
    await discoveryRepository.update(discovery.id, {
      status: 'failed',
      error: err instanceof Error ? err.message : 'Failed to read docs.md from sandbox',
    })
    return false
  } finally {
    // Discovery is a one-shot job — release the sandbox once docs.md is captured.
    try {
      await terminateModalSandbox(row.modalSandboxId)
    } catch (err) {
      logger.warn({ err, sandboxId: row.id }, 'Failed to terminate discovery sandbox')
    }
  }
}

const AUTO_BUILD_PROMPTS: Record<SandboxJobType, (name: string, language?: string) => string> = {
  sdk: (name, language) =>
    [
      `Build a production-grade ${language ?? 'SDK'} SDK for "${name}" from the API surface in /workspace/docs.md.`,
      'Follow the sdk-builder skill, including the versioning steps: set the package version from WELDRR_ARTIFACT_VERSION, commit, push, and tag.',
      'Implement typed clients for every listed endpoint, add a smoke test, and ensure lint/tests pass.',
      'Do not implement anything in the excluded internal section.',
    ].join(' '),
  docs: (name) =>
    [
      `Build the API documentation site for "${name}" from /workspace/docs.md and /workspace/spec.json.`,
      'Follow the docs-builder skill: populate the template pages, create a reference page per resource, and verify the build.',
      'Include the versioning steps: commit, push, and tag with WELDRR_ARTIFACT_VERSION.',
      'Do not document anything in the excluded internal section.',
    ].join(' '),
  discovery: () => '',
}

async function autoStartArtifactBuilds(project: Project, workspaceId: string): Promise<void> {
  const languages: SandboxLanguage[] = (project.sdkLanguages?.length
    ? project.sdkLanguages
    : ['typescript']) as SandboxLanguage[]

  const jobs: { jobType: 'sdk' | 'docs'; language?: SandboxLanguage }[] = [
    ...languages.map((language) => ({ jobType: 'sdk' as const, language })),
    { jobType: 'docs' as const },
  ]

  for (const job of jobs) {
    try {
      const sandbox = await sandboxService.issue(workspaceId, {
        projectId: project.id,
        jobType: job.jobType,
        language: job.language,
      })
      await sandboxService.start(workspaceId, sandbox.id, {
        prompt: AUTO_BUILD_PROMPTS[job.jobType](project.name, job.language),
      })
      logger.info(
        { projectId: project.id, jobType: job.jobType, language: job.language },
        'Auto-started build after discovery',
      )
    } catch (err) {
      logger.error(
        { err, projectId: project.id, jobType: job.jobType, language: job.language },
        'Failed to auto-start build after discovery',
      )
    }
  }
}

export async function issueDiscoverySandbox(projectId: string): Promise<void> {
  const project = await projectRepository.findByIdGlobal(projectId)
  if (!project) return

  const callbackToken = randomToken()
  const opencodePassword = randomToken()
  const baseUrl = publicBaseUrl()

  const discovery = await discoveryRepository.create({
    projectId: project.id,
    workspaceId: project.workspaceId,
    status: 'running',
  })

    const sandbox = await sandboxRepository.create({
      workspaceId: project.workspaceId,
      projectId: project.id,
      jobType: 'discovery',
      language: null,
      spec: null,
      status: 'issuing',
      modalSandboxId: null,
      tunnelUrl: null,
      opencodePassword: encryptSecret(opencodePassword),
      callbackTokenHash: sha256(callbackToken),
      error: null,
      startedAt: null,
      finishedAt: null,
    })

  await discoveryRepository.update(discovery.id, { sandboxId: sandbox.id })

  const callbackUrl = `${baseUrl}/api/sandboxes/callback`
  const bootstrapUrl = `${baseUrl}/api/sandboxes/${sandbox.id}/bootstrap?token=${callbackToken}`
  const gitTemplate = project.gitRepo?.cloneUrl ?? ''

  try {
    const provisioned = await provisionSandbox({
      sandboxId: sandbox.id,
      jobType: 'discovery',
      callbackUrl,
      callbackToken,
      bootstrapUrl,
      gitTemplate,
      opencodePassword,
      discoveryTarget: project.specUrl ?? undefined,
    })

    await sandboxRepository.update(project.workspaceId, sandbox.id, {
      status: 'ready',
      modalSandboxId: provisioned.sandboxId,
      tunnelUrl: provisioned.tunnelUrl,
      startedAt: new Date(),
    })

    await opencodeHealth(provisioned.tunnelUrl, opencodePassword)
    const sessionId = await opencodeCreateSession(
      provisioned.tunnelUrl,
      opencodePassword,
      `weldrr-discovery-${sandbox.id}`,
    )
    await opencodeSendPrompt(
      provisioned.tunnelUrl,
      opencodePassword,
      sessionId,
      discoveryPrompt({ name: project.name, targetUrl: project.specUrl }),
      discoveryAgentSystemPrompt(),
    )

    await sandboxRepository.update(project.workspaceId, sandbox.id, {
      status: 'building',
    })
    logger.info({ projectId, sandboxId: sandbox.id }, 'Discovery sandbox started')
  } catch (err) {
    logger.error({ err, projectId, sandboxId: sandbox.id }, 'Discovery sandbox failed')
    await sandboxRepository.update(project.workspaceId, sandbox.id, {
      status: 'failed',
      error: err instanceof Error ? err.message : 'Discovery sandbox provisioning failed',
      finishedAt: new Date(),
    })
    await discoveryRepository.update(discovery.id, {
      status: 'failed',
      error: err instanceof Error ? err.message : 'Discovery failed',
    })
  }
}
